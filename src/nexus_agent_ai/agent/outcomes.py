"""Bounded verified mutation evidence and disposable, deterministic history views."""
import json
import os
import re

from .memory import is_genuine_user_message

MAX_OUTCOME_FILES = 8
MAX_OUTCOME_METADATA_CHARS = 2048
_VERBS = r"(?:fixed|updated|changed|modified|patched|applied|corrected|replaced|rewrote|rewritten|edited|implemented|added|removed|renamed|resolved|created|written|wrote|saved|generated)"
_ACTIVE = re.compile(r"^\s*(?:[-*]\s+)?(?:I(?:'ve|\s+have)?\s+(?:(?:now|successfully|just)\s+)?)?" + _VERBS + r"\b\s+(?P<files>.+?)\s*[.!?;]?\s*$", re.IGNORECASE)
_PASSIVE = re.compile(r"^\s*(?:[-*]\s+)?(?P<files>.+?)\s+(?:was|were|is|are|has been|have been)\s+(?:(?:now|successfully|just)\s+)?" + _VERBS + r"[.!?;]?\s*$", re.IGNORECASE)
_FILE = re.compile(r"(?:[A-Za-z]:[\\/])?[\w./\\-]+\.[A-Za-z0-9]{1,8}(?!\w)")
_SEPARATOR = re.compile(r"\band\b|\bthe\s+(?:file|script|module)\b|[\s,`'\"]+", re.IGNORECASE)
_CLAUSES = re.compile(r".+?(?:[.!?](?=\s|$)|;|\n|$)", re.DOTALL)
_CODE = re.compile(r"(```.*?```|~~~.*?~~~)", re.DOTALL)
_CONJUNCTION = re.compile(r"\s+(?:and|but)\s+(?=(?:I\b|" + _VERBS + r"\b))", re.IGNORECASE)


def _path_key(path):
    # Lexical only: history inspection must not read or resolve files again.
    return os.path.normcase(os.path.abspath(path))


def mutation_metadata(outcomes):
    """Evidence is generated by the executor, never parsed from model claims/results."""
    records = []
    for path, status in list(outcomes.items())[-MAX_OUTCOME_FILES:]:
        if status not in ("changed", "unchanged") or len(path) > 256:
            continue
        record = {"path": path, "status": status}
        candidate = {"mutation_outcomes": records + [record]}
        if len(json.dumps(candidate, ensure_ascii=False)) <= MAX_OUTCOME_METADATA_CHARS:
            records.append(record)
    return {"mutation_outcomes": records}


def _redact_clause(clause, outcomes):
    match = _ACTIVE.fullmatch(clause) or _PASSIVE.fullmatch(clause)
    if not match:
        return clause, set()
    names = match.group("files").rstrip(".!?;")
    references = list(_FILE.finditer(names))
    # Only direct file objects/lists count. Proposals, examples, negations and
    # complex prose are unknown, not contradictions inferred from keyword proximity.
    remainder = _FILE.sub("", names)
    if not references or _SEPARATOR.sub("", remainder):
        return clause, set()
    contradicted = set()
    replacements = []
    for reference in references:
        path = _path_key(reference.group())
        status = outcomes.get(path)
        if status == "unchanged":
            contradicted.add(path)
            replacements.append((reference.start(), reference.end()))
    if not contradicted:
        return clause, set()
    if len(replacements) == len(references):
        return "[Contradicted file-change claim omitted.]" + ("\n" if clause.endswith("\n") else ""), contradicted
    # A shared predicate can name successful, failed and unknown files. Retain
    # the successful/unknown claims instead of deleting the entire sentence.
    start = match.start("files")
    redacted = clause
    for first, last in reversed(replacements):
        redacted = redacted[:start + first] + "[contradicted file reference omitted]" + redacted[start + last:]
    return redacted, contradicted


def _redact_text(text, outcomes):
    contradicted = set()
    pieces = _CODE.split(text)
    for index in range(0, len(pieces), 2):
        def replace_clause(match):
            parts = _CONJUNCTION.split(match.group())
            # Preserve conjunction bytes by changing only the matched clauses.
            result = match.group()
            offset = 0
            for part in parts:
                location = result.find(part, offset)
                replacement, false_paths = _redact_clause(part, outcomes)
                contradicted.update(false_paths)
                result = result[:location] + replacement + result[location + len(part):]
                offset = location + len(replacement)
            return result
        pieces[index] = _CLAUSES.sub(replace_clause, pieces[index])
    return "".join(pieces), contradicted


def fitted_claim_view(messages):
    """Never edit audit history or user text; append internal correction after tool results."""
    output = []
    starts = [i for i, message in enumerate(messages) if is_genuine_user_message(message)]
    boundaries = sorted(set([0, *starts, len(messages)]))
    for first, last in zip(boundaries, boundaries[1:]):
        segment = messages[first:last]
        evidence = {}
        for message in segment:
            metadata = message.get("metadata", {})
            if message.get("role") in ("assistant", "tool") and "mutation_outcomes" in metadata:
                evidence = {
                    _path_key(record["path"]): record["status"]
                    for record in metadata["mutation_outcomes"][:MAX_OUTCOME_FILES]
                    if isinstance(record, dict) and isinstance(record.get("path"), str)
                    and record.get("status") in ("changed", "unchanged")
                }
        false_paths = set()
        for message in segment:
            if message.get("role") == "assistant" and isinstance(message.get("content"), str):
                text, contradicted = _redact_text(message["content"], evidence)
                false_paths.update(contradicted)
                if text != message["content"]:
                    message = {**message, "content": text}
            output.append(message)
        if false_paths:
            # All entries are bounded executor observations, not generic CLI corrections.
            changed_paths = sorted(path for path, status in evidence.items() if status == "changed")
            facts = []
            if changed_paths:
                facts.append("Observed mutations: " + ", ".join(json.dumps(p, ensure_ascii=False) for p in changed_paths))
            facts.append("No mutation observed: " + ", ".join(json.dumps(p, ensure_ascii=False) for p in sorted(false_paths)))
            output.append({
                "role": "user",
                "content": "Historical tool outcomes only, not a new request or approval. " + "; ".join(facts) + ".",
                "metadata": {"internal": True, "outcome_correction": True},
            })
    return output
