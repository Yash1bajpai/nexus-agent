# proof_gate_evaluate.py
"""Nexus e2e — P1-P3 Explicit Prerequisite Gate Evaluator.

Evaluates evidence artifacts generated by probe-timeout and probe-account jobs
prior to executing the P1-P3 narrow proof. Operates strictly fail-closed: any
missing file, unparseable JSON, missing key, type mismatch, or failed fact
causes an immediate non-zero exit (exit 1).

Never reads job status/conclusions or needs.*.result (F2d).
All facts are verified from artifact data on disk.
Always writes proof_gate_eval.json with fact evaluation details and carries
observed_phase_b_no_survivors verbatim as context.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
from typing import Any

CONTAINMENT_NOTE = (
    "if:always cleanup covers STEP-level failure/timeout only; "
    "JOB-level cancellation leaves disposable-VM teardown as the sole outer bound; "
    "the frozen 15m-step-in-30m-job reserve is the mitigation."
)

VALID_COVERAGE_ENUM = ("known_lineage_observed", "blind_window")
VALID_COVERAGE_PHASES = ("Phase A", "Phase B", "Phase C")


def _load_json(path: Path) -> tuple[dict[str, Any] | None, str | None]:
    if not path.is_file():
        return None, f"File missing: {path}"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            return None, f"Expected JSON object in {path}, got {type(data).__name__}"
        return data, None
    except Exception as e:
        return None, f"Failed to parse JSON in {path}: {e}"


def evaluate_prerequisites(evidence_root: Path) -> tuple[bool, dict[str, Any]]:
    facts: dict[str, dict[str, Any]] = {}
    errors: list[str] = []
    observed_phase_b_context: Any = None

    timeout_dir = evidence_root / "timeout"
    account_dir = evidence_root / "account"

    survivor_log_path = timeout_dir / "survivor_check_step.log"
    probe_timeout_log_path = timeout_dir / "probe_timeout.log"
    verification_json_path = timeout_dir / "probe_timeout_verification.json"
    account_cleanup_json_path = account_dir / "probe_account_cleanup.json"
    account_receipt_json_path = account_dir / "probe_account_receipt.json"

    # -------------------------------------------------------------------------
    # Fact 1: survivor_check_step.log contains EXACTLY ONE SURVIVOR_CHECK line
    # -------------------------------------------------------------------------
    r_record: dict[str, Any] | None = None
    if not survivor_log_path.is_file():
        facts["1_survivor_check_record_present_exact1"] = {
            "pass": False,
            "error": f"File missing: {survivor_log_path}",
        }
        errors.append(f"Fact 1 failed: file missing {survivor_log_path}")
    else:
        try:
            lines = survivor_log_path.read_text(encoding="utf-8", errors="replace").splitlines()
            match_lines = [line for line in lines if line.startswith("SURVIVOR_CHECK: ")]
            if len(match_lines) != 1:
                facts["1_survivor_check_record_present_exact1"] = {
                    "pass": False,
                    "count": len(match_lines),
                    "error": f"Expected exactly 1 'SURVIVOR_CHECK: ' line, found {len(match_lines)}",
                }
                errors.append(f"Fact 1 failed: found {len(match_lines)} SURVIVOR_CHECK lines")
            else:
                json_str = match_lines[0][len("SURVIVOR_CHECK: "):]
                parsed = json.loads(json_str)
                if not isinstance(parsed, dict):
                    facts["1_survivor_check_record_present_exact1"] = {
                        "pass": False,
                        "error": f"Parsed SURVIVOR_CHECK is not a JSON object: {type(parsed).__name__}",
                    }
                    errors.append("Fact 1 failed: SURVIVOR_CHECK record is not a dict")
                else:
                    r_record = parsed
                    observed_phase_b_context = r_record.get("observed_phase_b_no_survivors")
                    facts["1_survivor_check_record_present_exact1"] = {
                        "pass": True,
                        "observed_line": match_lines[0],
                    }
        except Exception as e:
            facts["1_survivor_check_record_present_exact1"] = {
                "pass": False,
                "error": f"Exception reading {survivor_log_path}: {e}",
            }
            errors.append(f"Fact 1 failed: {e}")

    # -------------------------------------------------------------------------
    # Fact 2: R schema validity
    # -------------------------------------------------------------------------
    if r_record is None:
        facts["2_survivor_record_schema_valid"] = {
            "pass": False,
            "error": "Cannot evaluate schema: SURVIVOR_CHECK record missing",
        }
        errors.append("Fact 2 failed: record missing")
    else:
        f2_errors: list[str] = []
        nonce_val = r_record.get("nonce")
        coverage_val = r_record.get("coverage")
        cov_phases_val = r_record.get("coverage_phases")
        full_tree_val = r_record.get("full_tree_containment_proven")

        if not isinstance(nonce_val, str) or len(nonce_val.strip()) == 0:
            f2_errors.append("nonce must be non-empty string")

        if coverage_val not in VALID_COVERAGE_ENUM:
            f2_errors.append(
                f"coverage must be one of {VALID_COVERAGE_ENUM}, got {coverage_val!r}"
            )

        if not isinstance(cov_phases_val, list):
            f2_errors.append("coverage_phases must be a list")
        else:
            invalid_phases = [p for p in cov_phases_val if not isinstance(p, str) or p not in VALID_COVERAGE_PHASES]
            if invalid_phases:
                f2_errors.append(
                    f"coverage_phases members must be from {VALID_COVERAGE_PHASES}, invalid: {invalid_phases!r}"
                )

        if full_tree_val is not False:
            f2_errors.append(f"full_tree_containment_proven must be False, got {full_tree_val!r}")

        if "observed_phase_b_no_survivors" not in r_record or not isinstance(r_record["observed_phase_b_no_survivors"], bool):
            f2_errors.append(
                f"observed_phase_b_no_survivors must be a boolean (True or False), got {r_record.get('observed_phase_b_no_survivors')!r}"
            )

        f2_pass = len(f2_errors) == 0
        facts["2_survivor_record_schema_valid"] = {
            "pass": f2_pass,
            "nonce": nonce_val,
            "coverage": coverage_val,
            "coverage_phases": cov_phases_val,
            "full_tree_containment_proven": full_tree_val,
            "observed_phase_b_no_survivors": r_record.get("observed_phase_b_no_survivors"),
            "errors": f2_errors if not f2_pass else [],
        }
        if not f2_pass:
            errors.append(f"Fact 2 failed: {'; '.join(f2_errors)}")

    # -------------------------------------------------------------------------
    # Fact 3: Conclusive phases and zero unknown/reused
    # -------------------------------------------------------------------------
    if r_record is None:
        facts["3_phases_conclusive_zero_unknown_reused"] = {
            "pass": False,
            "error": "Cannot evaluate phases: SURVIVOR_CHECK record missing",
        }
        errors.append("Fact 3 failed: record missing")
    else:
        f3_errors: list[str] = []
        phase_observations: dict[str, Any] = {}

        for p in ("a", "b", "c"):
            phase_key = f"phase_{p}"
            phase_obj = r_record.get(phase_key)
            if not isinstance(phase_obj, dict):
                f3_errors.append(f"{phase_key} missing or not a dict")
                continue

            conclusive = phase_obj.get("conclusive")
            if conclusive is not True:
                f3_errors.append(f"{phase_key}.conclusive is not True ({conclusive!r})")

            scan_obj = phase_obj.get("scan")
            if not isinstance(scan_obj, dict):
                f3_errors.append(f"{phase_key}.scan missing or not a dict")
                continue

            unknown_list = scan_obj.get("unknown")
            reused_list = scan_obj.get("reused")

            if not isinstance(unknown_list, list) or len(unknown_list) != 0:
                f3_errors.append(f"{phase_key}.scan.unknown must be empty list, got {unknown_list!r}")
            if not isinstance(reused_list, list) or len(reused_list) != 0:
                f3_errors.append(f"{phase_key}.scan.reused must be empty list, got {reused_list!r}")

            phase_observations[phase_key] = {
                "conclusive": conclusive,
                "unknown_count": len(unknown_list) if isinstance(unknown_list, list) else None,
                "reused_count": len(reused_list) if isinstance(reused_list, list) else None,
            }

        # Strict Phase C requirements (no legacy fallback)
        phase_c_obj = r_record.get("phase_c")
        if isinstance(phase_c_obj, dict):
            c_scan = phase_c_obj.get("scan")
            if isinstance(c_scan, dict):
                survivors_c = c_scan.get("survivors")
                if not isinstance(survivors_c, list) or len(survivors_c) != 0:
                    f3_errors.append(f"phase_c.scan.survivors must be empty list, got {survivors_c!r}")
                phase_observations["phase_c"]["survivors_count"] = (
                    len(survivors_c) if isinstance(survivors_c, list) else None
                )

            # Strict: observed_snapshot_clean REQUIRED True (no legacy clean fallback)
            c_clean = phase_c_obj.get("observed_snapshot_clean")
            if c_clean is not True:
                f3_errors.append(f"phase_c.observed_snapshot_clean is not True ({c_clean!r})")
            phase_observations["phase_c"]["observed_snapshot_clean"] = c_clean

        f3_pass = len(f3_errors) == 0
        facts["3_phases_conclusive_zero_unknown_reused"] = {
            "pass": f3_pass,
            "phases": phase_observations,
            "errors": f3_errors if not f3_pass else [],
        }
        if not f3_pass:
            errors.append(f"Fact 3 failed: {'; '.join(f3_errors)}")

    # -------------------------------------------------------------------------
    # Fact 4: Cleanup integrity
    # -------------------------------------------------------------------------
    if r_record is None:
        facts["4_cleanup_integrity_valid"] = {
            "pass": False,
            "error": "Cannot evaluate cleanup: SURVIVOR_CHECK record missing",
        }
        errors.append("Fact 4 failed: record missing")
    else:
        f4_errors: list[str] = []
        unowned_refused = r_record.get("cleanup_unowned_refused")
        cleanup_kills = r_record.get("cleanup_kills")

        if not isinstance(unowned_refused, list) or len(unowned_refused) != 0:
            f4_errors.append(f"cleanup_unowned_refused must be empty list, got {unowned_refused!r}")

        if not isinstance(cleanup_kills, list):
            f4_errors.append(f"cleanup_kills must be a list, got {type(cleanup_kills).__name__}")
        else:
            for idx, k in enumerate(cleanup_kills):
                if not isinstance(k, dict):
                    f4_errors.append(f"cleanup_kills[{idx}] is not a dict")
                elif k.get("status") != "terminated":
                    f4_errors.append(
                        f"cleanup_kills[{idx}] pid={k.get('pid')} has status {k.get('status')!r} (expected 'terminated')"
                    )

        f4_pass = len(f4_errors) == 0
        facts["4_cleanup_integrity_valid"] = {
            "pass": f4_pass,
            "unowned_refused_count": len(unowned_refused) if isinstance(unowned_refused, list) else None,
            "cleanup_kills_count": len(cleanup_kills) if isinstance(cleanup_kills, list) else None,
            "errors": f4_errors if not f4_pass else [],
        }
        if not f4_pass:
            errors.append(f"Fact 4 failed: {'; '.join(f4_errors)}")

    # -------------------------------------------------------------------------
    # Fact 5: Nonce chain verification
    # -------------------------------------------------------------------------
    f5_errors: list[str] = []
    start_nonce: str | None = None
    beat_nonces: set[str] = set()
    verification_nonce: str | None = None
    r_nonce: str | None = r_record.get("nonce") if r_record else None

    # (a) & (b) from probe_timeout.log
    if not probe_timeout_log_path.is_file():
        f5_errors.append(f"File missing: {probe_timeout_log_path}")
    else:
        try:
            log_lines = probe_timeout_log_path.read_text(encoding="utf-8", errors="replace").splitlines()
            start_lines = [line for line in log_lines if line.startswith("START ")]
            if len(start_lines) != 1:
                f5_errors.append(f"Expected exactly 1 START line in probe_timeout.log, found {len(start_lines)}")
            else:
                for token in start_lines[0].split():
                    if token.startswith("nonce="):
                        val = token.split("=")[1].strip()
                        if val:
                            start_nonce = val
                if start_nonce is None:
                    f5_errors.append("START line missing non-empty nonce= token")

            beat_lines = [line for line in log_lines if line.startswith("BEAT ")]
            if len(beat_lines) == 0:
                f5_errors.append("Zero BEAT lines in probe_timeout.log")
            else:
                for idx, line in enumerate(beat_lines):
                    b_nonce: str | None = None
                    for token in line.split():
                        if token.startswith("nonce="):
                            parts = token.split("=", 1)
                            if len(parts) == 2 and len(parts[1].strip()) > 0:
                                b_nonce = parts[1].strip()
                    if b_nonce is None:
                        f5_errors.append(f"BEAT line #{idx} missing non-empty nonce: {line!r}")
                    else:
                        beat_nonces.add(b_nonce)

            if len(beat_nonces) > 1:
                f5_errors.append(f"Multiple conflicting nonces across BEAT lines: {sorted(beat_nonces)}")
        except Exception as e:
            f5_errors.append(f"Failed to read {probe_timeout_log_path}: {e}")

    # (c) R["nonce"] already captured as r_nonce
    if r_nonce is None or len(r_nonce.strip()) == 0:
        f5_errors.append("R['nonce'] is missing or empty")

    # (d) from probe_timeout_verification.json
    v_data, v_err = _load_json(verification_json_path)
    if v_err:
        f5_errors.append(f"Verification JSON error: {v_err}")
    elif v_data is not None:
        v_nonce_val = v_data.get("nonce")
        if not isinstance(v_nonce_val, str) or len(v_nonce_val.strip()) == 0:
            f5_errors.append("probe_timeout_verification.json missing valid nonce")
        else:
            verification_nonce = v_nonce_val

    # Equality check across all nonces
    sole_beat_nonce = next(iter(beat_nonces)) if len(beat_nonces) == 1 else None
    all_nonces = {start_nonce, sole_beat_nonce, r_nonce, verification_nonce}
    if None in all_nonces or len(all_nonces) != 1 or len(f5_errors) > 0:
        if len(all_nonces) > 1:
            f5_errors.append(f"Nonce mismatch across evidence sources: {sorted(str(n) for n in all_nonces)}")
        f5_pass = False
    else:
        f5_pass = True

    facts["5_nonce_chain_verified"] = {
        "pass": f5_pass,
        "start_nonce": start_nonce,
        "beat_nonces": sorted(beat_nonces),
        "survivor_record_nonce": r_nonce,
        "verification_nonce": verification_nonce,
        "errors": f5_errors if not f5_pass else [],
    }
    if not f5_pass:
        errors.append(f"Fact 5 failed: {'; '.join(f5_errors)}")

    # -------------------------------------------------------------------------
    # Fact 6: Account leg verification
    # -------------------------------------------------------------------------
    f6_errors: list[str] = []
    receipt_sid: str | None = None
    cleanup_target_sid: str | None = None

    r_data, r_err = _load_json(account_receipt_json_path)
    if r_err:
        f6_errors.append(f"Account receipt error: {r_err}")
    elif r_data is not None:
        receipt_sid = r_data.get("sid")
        if not isinstance(receipt_sid, str) or len(receipt_sid.strip()) == 0:
            f6_errors.append("probe_account_receipt.json missing valid sid")

    c_data, c_err = _load_json(account_cleanup_json_path)
    if c_err:
        f6_errors.append(f"Account cleanup error: {c_err}")
    elif c_data is not None:
        cleanup_target_sid = c_data.get("target_sid")
        if c_data.get("account_deleted") is not True:
            f6_errors.append(f"account_deleted is not True ({c_data.get('account_deleted')!r})")

        post_sweep = c_data.get("post_sweep")
        if not isinstance(post_sweep, dict):
            f6_errors.append("post_sweep missing or not a dict")
        else:
            if post_sweep.get("clean") is not True:
                f6_errors.append(f"post_sweep.clean is not True ({post_sweep.get('clean')!r})")
            if post_sweep.get("child_pids") != []:
                f6_errors.append(f"post_sweep.child_pids must be [], got {post_sweep.get('child_pids')!r}")
            if post_sweep.get("indeterminate_pids") != []:
                f6_errors.append(
                    f"post_sweep.indeterminate_pids must be [], got {post_sweep.get('indeterminate_pids')!r}"
                )

        if receipt_sid is not None and cleanup_target_sid != receipt_sid:
            f6_errors.append(
                f"target_sid in cleanup ({cleanup_target_sid!r}) does not match receipt sid ({receipt_sid!r})"
            )

    f6_pass = len(f6_errors) == 0
    facts["6_account_lifecycle_clean"] = {
        "pass": f6_pass,
        "receipt_sid": receipt_sid,
        "cleanup_target_sid": cleanup_target_sid,
        "errors": f6_errors if not f6_pass else [],
    }
    if not f6_pass:
        errors.append(f"Fact 6 failed: {'; '.join(f6_errors)}")

    # -------------------------------------------------------------------------
    # Overall evaluation
    # -------------------------------------------------------------------------
    all_facts_pass = (
        facts.get("1_survivor_check_record_present_exact1", {}).get("pass") is True
        and facts.get("2_survivor_record_schema_valid", {}).get("pass") is True
        and facts.get("3_phases_conclusive_zero_unknown_reused", {}).get("pass") is True
        and facts.get("4_cleanup_integrity_valid", {}).get("pass") is True
        and facts.get("5_nonce_chain_verified", {}).get("pass") is True
        and facts.get("6_account_lifecycle_clean", {}).get("pass") is True
    )

    eval_result: dict[str, Any] = {
        "overall_pass": all_facts_pass,
        "containment_note": CONTAINMENT_NOTE,
        "observed_phase_b_no_survivors": observed_phase_b_context,
        "facts": facts,
        "errors": errors,
    }

    return all_facts_pass, eval_result


def main() -> int:
    parser = argparse.ArgumentParser(description="Nexus P1-P3 Explicit Prerequisite Gate Evaluator")
    parser.add_argument(
        "--evidence-root",
        default="probe_evidence",
        help="Root path containing timeout/ and account/ artifact directories",
    )
    parser.add_argument(
        "--out",
        default="proof_gate_eval.json",
        help="Destination path for evaluation summary JSON",
    )
    args = parser.parse_args()

    evidence_root = Path(args.evidence_root).resolve()
    out_path = Path(args.out).resolve()

    overall_pass, eval_result = evaluate_prerequisites(evidence_root)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(eval_result, indent=2), encoding="utf-8")
    print(f"PROOF_GATE_EVAL: written to {out_path}", flush=True)

    if overall_pass:
        print("PROOF_GATE_EVAL: PASS — All explicit prerequisite facts verified.", flush=True)
        return 0
    else:
        print("PROOF_GATE_EVAL: FAIL — One or more prerequisite facts failed:", file=sys.stderr, flush=True)
        for err in eval_result.get("errors", []):
            print(f"  - {err}", file=sys.stderr, flush=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
